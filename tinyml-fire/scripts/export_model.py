"""Export exactly the trained 2->8->1 network; no training or synthetic weights."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def write_model(w1, b1, w2, b2, source, out, mean=(0, 0), scale=(1, 1)):
    import numpy as np
    arrays = [np.asarray(a, dtype=np.float32) for a in (w1, b1, w2, b2)]
    if [a.shape for a in arrays] != [(2, 8), (8,), (8, 1), (1,)]:
        raise ValueError("Only Dense(2->8 relu->1 sigmoid) is supported")
    if any(not np.isfinite(a).all() for a in arrays):
        raise ValueError("Weights must be finite")
    if len(mean) != 2 or len(scale) != 2 or not np.isfinite([mean, scale]).all() or min(scale) <= 0:
        raise ValueError("Invalid preprocessing")
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    digest = hashlib.sha256(Path(source).read_bytes()).hexdigest()
    obj = dict(id=digest[:12], source_sha256=digest, architecture="2-8-1/relu/sigmoid",
               mean=list(mean), scale=list(scale), w1=arrays[0].tolist(), b1=arrays[1].tolist(),
               w2=arrays[2].reshape(8).tolist(), b2=float(arrays[3][0]))
    (out / "model.json").write_text(json.dumps(obj, indent=2) + "\n", encoding="utf-8")

    def num(v):
        s = format(float(v), ".9g")
        if "." not in s and "e" not in s:
            s += ".0"
        return s + "f"

    def row(a):
        return "{" + ", ".join(num(v) for v in a) + "}"

    header = "#pragma once\n// Generated by scripts/export_model.py. Do not hand-edit.\n"
    header += "namespace tinyfire { namespace weights {\n"
    header += 'static const char id[] = "' + obj["id"] + '";\n'
    header += "static const float mean[2] = " + row(mean) + ";\n"
    header += "static const float scale[2] = " + row(scale) + ";\n"
    header += "static const float w1[2][8] = {" + ",".join(row(r) for r in arrays[0]) + "};\n"
    header += "static const float b1[8] = " + row(arrays[1]) + ";\n"
    header += "static const float w2[8] = " + row(arrays[2].reshape(8)) + ";\n"
    header += "static const float b2 = " + num(arrays[3][0]) + ";\n}}\n"
    (out / "model_weights.h").write_text(header, encoding="utf-8")
    return obj


def export_h5(source, out):
    import h5py
    import numpy as np
    with h5py.File(source, "r") as f:
        cfg = json.loads(f.attrs["model_config"])
        layers = cfg["config"]["layers"]
        if [l["class_name"] for l in layers] != ["InputLayer", "Dense", "Dense"]:
            raise ValueError("Unexpected model architecture")
        if [l["config"]["activation"] for l in layers[1:]] != ["relu", "sigmoid"]:
            raise ValueError("Unexpected activations")
        values = []
        for layer in layers[1:]:
            group = f["model_weights"][layer["config"]["name"]]
            found = {}
            def collect(name, item):
                if isinstance(item, h5py.Dataset):
                    found[name.rsplit("/", 1)[-1].split(":")[0]] = np.asarray(item)
            group.visititems(collect)
            values.extend([found["kernel"], found["bias"]])
    return write_model(*values, source=source, out=out)


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--source", type=Path, default=ROOT / "models/TinyML.h5")
    p.add_argument("--out", type=Path, default=ROOT / "models/exported")
    p.add_argument("--install", action="store_true", help="Copy exported header into this module's firmware")
    args = p.parse_args()
    result = export_h5(args.source, args.out)
    if args.install:
        raise SystemExit("Legacy H5 is reference-only. Use train_temperature_model.py --install for current firmware.")
    print("Exported model", result["id"])
